/**
 * Busca un término del glosario a partir de una palabra o frase
 */
export function findGlossaryItem(wordOrAlias: string): GlossaryItem | undefined {
  const normalized = wordOrAlias.trim().toLowerCase();
  return GLOSSARY_ITEMS.find(
    (item) =>
      item.id === normalized ||
      item.term.toLowerCase().includes(normalized) ||
      item.aliases.some((alias) => alias.toLowerCase() === normalized)
  );
}
